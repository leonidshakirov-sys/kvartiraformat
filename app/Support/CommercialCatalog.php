    /**
     * @param array<string,mixed> $dbRow
     * @return array<string,mixed>
     */
    public static function merge(?array $dbRow, array $catalog): array
    {
        if (!$dbRow) {
            return $catalog;
        }
        foreach (['title', 'short', 'body', 'image_path', 'image_alt', 'meta_title', 'meta_description', 'h1'] as $key) {
            $value = trim((string)($dbRow[$key] ?? ''));
            if ($value !== '') {
                $catalog[$key] = $dbRow[$key];
            }
        }
        foreach (['id', 'price', 'is_published', 'sort_order', 'slug', 'category'] as $key) {
            if (array_key_exists($key, $dbRow) && $dbRow[$key] !== null && $dbRow[$key] !== '') {
                $catalog[$key] = $dbRow[$key];
            }
        }
        return $catalog;
    }

